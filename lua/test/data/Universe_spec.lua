local Universe = require("multiverse.data.Universe")

describe("Universe", function()
	describe("new", function()
		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new(12345)
				end, "Universe:new requires a table argument")
			end)
		end)

		describe("with no argument", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new()
				end, "Universe:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a missing uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ name = "name-1", workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = 123, name = "name-1", workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with an empty string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "", name = "name-1", workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a missing name", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with a non-string name", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", name = 123, workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with an empty string name", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", name = "", workingDirectory = "/dir-1" })
				end, "Universe:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with a missing workingDirectory", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", name = "name-1" })
				end, "Universe:new requires opts.workingDirectory to be a non-empty string")
			end)
		end)

		describe("with a non-string workingDirectory", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", name = "name-1", workingDirectory = 123 })
				end, "Universe:new requires opts.workingDirectory to be a non-empty string")
			end)
		end)

		describe("with an empty string workingDirectory", function()
			it("should raise", function()
				assert.has_error(function()
					Universe:new({ uuid = "uuid-1", name = "name-1", workingDirectory = "" })
				end, "Universe:new requires opts.workingDirectory to be a non-empty string")
			end)
		end)

		describe("with valid opts", function()
			it("should map fields and initialize defaults", function()
				local universe = Universe:new({ uuid = "uuid-1", name = "name-1", workingDirectory = "/dir-1" })

				assert.are.equal("uuid-1", universe.uuid)
				assert.are.equal("name-1", universe.name)
				assert.are.equal("/dir-1", universe.workingDirectory)
				assert.is_nil(universe.currentTabpage)
				assert.are.same({}, universe.buffers)
				assert.are.same({}, universe.tabpages)
			end)
		end)
	end)
end)
