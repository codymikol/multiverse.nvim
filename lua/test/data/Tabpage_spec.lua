local Tabpage = require("multiverse.data.Tabpage")

describe("Tabpage", function()
	describe("new", function()
		describe("with a missing uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Tabpage:new({})
				end, "Tabpage:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Tabpage:new({ uuid = 123 })
				end, "Tabpage:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with an empty string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Tabpage:new({ uuid = "" })
				end, "Tabpage:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					Tabpage:new("tabpage-1-uuid")
				end, "Tabpage:new requires a table argument")
			end)
		end)

		describe("with a valid uuid, tabpageId, and activeWindowUuid", function()
			it("should map fields", function()
				local tabpage = Tabpage:new({ uuid = "tabpage-1-uuid", tabpageId = 1, activeWindowUuid = "window-1-uuid" })

				assert.are.equal("tabpage-1-uuid", tabpage.uuid)
				assert.are.equal(1, tabpage.tabpageId)
				assert.are.equal("window-1-uuid", tabpage.activeWindowUuid)
				assert.are.same({}, tabpage.windows)
				assert.is_nil(tabpage.layout)
			end)
		end)

		describe("with tabpageId and activeWindowUuid omitted", function()
			it("should map fields and leave them nil", function()
				local tabpage = Tabpage:new({ uuid = "tabpage-1-uuid" })

				assert.are.equal("tabpage-1-uuid", tabpage.uuid)
				assert.is_nil(tabpage.tabpageId)
				assert.is_nil(tabpage.activeWindowUuid)
			end)
		end)
	end)
end)
