local Window = require("multiverse.data.Window")

describe("Window", function()
	describe("new", function()
		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					Window:new(12345)
				end, "Window:new requires a table argument")
			end)
		end)

		describe("with a missing uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Window:new({ bufferUuid = "buf-uuid-1", windowId = 1 })
				end, "Window:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Window:new({ uuid = 123 })
				end, "Window:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with an empty string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Window:new({ uuid = "" })
				end, "Window:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with valid opts", function()
			it("should set uuid, bufferUuid and windowId", function()
				local w = Window:new({ uuid = "uuid-1", bufferUuid = "buf-uuid-1", windowId = 1 })
				assert.are.equal("uuid-1", w.uuid)
				assert.are.equal("buf-uuid-1", w.bufferUuid)
				assert.are.equal(1, w.windowId)
			end)

			it("should not expose a setBufferId method", function()
				local w = Window:new({ uuid = "uuid-1", bufferUuid = "buf-uuid-1", windowId = 1 })
				assert.is_nil(w.setBufferId)
			end)

			it("should tolerate a nil bufferUuid and windowId", function()
				local w = Window:new({ uuid = "uuid-1" })
				assert.are.equal("uuid-1", w.uuid)
				assert.is_nil(w.bufferUuid)
				assert.is_nil(w.windowId)
			end)
		end)
	end)
end)
