local stub = require("luassert.stub")

local UniverseSummary = require("multiverse.data.UniverseSummary")
local timestamp_manager = require("multiverse.managers.timestamp_manager")

describe("UniverseSummary", function()
	describe("new", function()
		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new(12345)
				end, "UniverseSummary:new requires a table argument")
			end)
		end)

		describe("with a missing directory", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ uuid = "uuid-1", name = "name-1" })
				end, "UniverseSummary:new requires opts.directory to be a non-empty string")
			end)
		end)

		describe("with a missing uuid", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", name = "name-1" })
				end, "UniverseSummary:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a missing name", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1" })
				end, "UniverseSummary:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with a non-string directory", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = 123, uuid = "uuid-1", name = "name-1" })
				end, "UniverseSummary:new requires opts.directory to be a non-empty string")
			end)
		end)

		describe("with an empty string directory", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "", uuid = "uuid-1", name = "name-1" })
				end, "UniverseSummary:new requires opts.directory to be a non-empty string")
			end)
		end)

		describe("with a non-string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", uuid = 123, name = "name-1" })
				end, "UniverseSummary:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with an empty string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", uuid = "", name = "name-1" })
				end, "UniverseSummary:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-string name", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = 123 })
				end, "UniverseSummary:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with an empty string name", function()
			it("should raise", function()
				assert.has_error(function()
					UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "" })
				end, "UniverseSummary:new requires opts.name to be a non-empty string")
			end)
		end)

		describe("with valid opts", function()
			it("should map fields and leave lastExplored nil when omitted", function()
				local universe = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1" })

				assert.are.equal("/dir-1", universe.directory)
				assert.are.equal("uuid-1", universe.uuid)
				assert.are.equal("name-1", universe.name)
				assert.is_nil(universe.lastExplored)
			end)
		end)
	end)

	describe("setLastExploredToNow", function()
		local now_stub

		before_each(function()
			now_stub = stub(timestamp_manager, "now").returns(1234)
		end)

		after_each(function()
			now_stub:revert()
		end)

		it("should set lastExplored to the current timestamp and return self", function()
			local universe = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local result = universe:setLastExploredToNow()

			assert.are.equal(1234, universe.lastExplored)
			assert.are.equal(universe, result)
		end)
	end)
end)
