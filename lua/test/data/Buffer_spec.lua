local Buffer = require("multiverse.data.Buffer")

describe("Buffer", function()
	describe("new", function()
		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new(12345)
				end, "Buffer:new requires a table argument")
			end)
		end)

		describe("with no argument", function()
			it("should raise a missing uuid error via the opts = opts or {} fallback", function()
				assert.has_error(function()
					Buffer:new()
				end, "Buffer:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a missing uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ bufferName = "name-1" })
				end, "Buffer:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a missing bufferName", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ uuid = "uuid-1" })
				end, "Buffer:new requires opts.bufferName to be a non-empty string")
			end)
		end)

		describe("with a non-string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ uuid = 123, bufferName = "name-1" })
				end, "Buffer:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with a non-string bufferName", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ uuid = "uuid-1", bufferName = 123 })
				end, "Buffer:new requires opts.bufferName to be a non-empty string")
			end)
		end)

		describe("with an empty string uuid", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ uuid = "", bufferName = "name-1" })
				end, "Buffer:new requires opts.uuid to be a non-empty string")
			end)
		end)

		describe("with an empty string bufferName", function()
			it("should raise", function()
				assert.has_error(function()
					Buffer:new({ uuid = "uuid-1", bufferName = "" })
				end, "Buffer:new requires opts.bufferName to be a non-empty string")
			end)
		end)

		describe("with a nil bufferId", function()
			it("should not raise and leave bufferId nil", function()
				local buffer = Buffer:new({ uuid = "uuid-1", bufferName = "name-1" })

				assert.is_nil(buffer.bufferId)
			end)
		end)

		describe("with valid opts", function()
			it("should map fields", function()
				local buffer = Buffer:new({ uuid = "uuid-1", bufferId = 42, bufferName = "name-1" })

				assert.are.equal("uuid-1", buffer.uuid)
				assert.are.equal(42, buffer.bufferId)
				assert.are.equal("name-1", buffer.bufferName)
			end)
		end)
	end)
end)
