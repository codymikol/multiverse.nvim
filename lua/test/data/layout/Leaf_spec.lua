local Leaf = require("multiverse.data.layout.Leaf")

describe("Leaf", function()
	describe("new", function()
		describe("with a missing windowUuid", function()
			it("should raise", function()
				assert.has_error(function()
					Leaf:new({})
				end, "Leaf:new requires opts.windowUuid to be a non-empty string")
			end)
		end)

		describe("with a non-string windowUuid", function()
			it("should raise", function()
				assert.has_error(function()
					Leaf:new({ windowUuid = 123 })
				end, "Leaf:new requires opts.windowUuid to be a non-empty string")
			end)
		end)

		describe("with an empty string windowUuid", function()
			it("should raise", function()
				assert.has_error(function()
					Leaf:new({ windowUuid = "" })
				end, "Leaf:new requires opts.windowUuid to be a non-empty string")
			end)
		end)

		describe("with a non-table argument", function()
			it("should raise", function()
				assert.has_error(function()
					Leaf:new(12345)
				end, "Leaf:new requires a table argument")
			end)
		end)

		describe("with a valid windowUuid and windowId", function()
			it("should map fields", function()
				local leaf = Leaf:new({ windowUuid = "window-1-uuid", windowId = 1 })

				assert.are.equal("leaf", leaf.type)
				assert.are.equal("window-1-uuid", leaf.windowUuid)
				assert.are.equal(1, leaf.windowId)
			end)
		end)

		describe("with a valid windowUuid and windowId omitted", function()
			it("should map fields and leave windowId nil", function()
				local leaf = Leaf:new({ windowUuid = "window-1-uuid" })

				assert.are.equal("leaf", leaf.type)
				assert.are.equal("window-1-uuid", leaf.windowUuid)
				assert.is_nil(leaf.windowId)
			end)
		end)
	end)
end)
