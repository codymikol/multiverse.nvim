local Multiverse = require("multiverse.data.Multiverse")
local UniverseSummary = require("multiverse.data.UniverseSummary")

describe("Multiverse", function()
	it("new should set universes", function()
		local universes = {
			UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 }),
		}
		local m = Multiverse:new(universes)
		assert.are.equal(universes, m.universes)
	end)

	it("getUniverseByDirectory should raise when universes was never set", function()
		local m = Multiverse:new(nil)
		assert.has_error(function()
			m:getUniverseByDirectory("/dir-1")
		end)
	end)

	it("addUniverse should append a universe to universes", function()
		local m = Multiverse:new({})
		local universe = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
		m:addUniverse(universe)
		assert.are.equal(1, #m.universes)
		assert.are.equal(universe, m.universes[1])
	end)

	it("addUniverse should append to a non-empty universes list", function()
		local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
		local m = Multiverse:new({ universe1 })
		local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-2", lastExplored = 2 })
		m:addUniverse(universe2)
		assert.are.equal(2, #m.universes)
		assert.are.equal(universe1, m.universes[1])
		assert.are.equal(universe2, m.universes[2])
	end)

	describe("getUniverseByDirectory", function()
		it("should return the universe matching the directory", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-2", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			assert.are.equal(universe2, m:getUniverseByDirectory("/dir-2"))
		end)

		it("should return nil when no universe matches the directory", function()
			local m = Multiverse:new({})
			assert.is_nil(m:getUniverseByDirectory("/missing"))
		end)

		it("should return the first match when directories are duplicated", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-2", name = "name-2", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			assert.are.equal(universe1, m:getUniverseByDirectory("/dir-1"))
		end)
	end)

	describe("getUniverseByName", function()
		it("should return the universe matching the name", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-2", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			assert.are.equal(universe1, m:getUniverseByName("name-1"))
		end)

		it("should return nil when no universe matches the name", function()
			local m = Multiverse:new({})
			assert.is_nil(m:getUniverseByName("missing"))
		end)

		it("should return the first match when names are duplicated", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-1", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			assert.are.equal(universe1, m:getUniverseByName("name-1"))
		end)
	end)

	describe("removeUniverse", function()
		it("should remove the universe matching the name", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-2", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			m:removeUniverse("name-1")
			assert.are.equal(1, #m.universes)
			assert.are.equal(universe2, m.universes[1])
		end)

		it("should do nothing when no universe matches the name", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local m = Multiverse:new({ universe1 })
			m:removeUniverse("missing")
			assert.are.equal(1, #m.universes)
			assert.are.equal(universe1, m.universes[1])
		end)

		it("should remove only the first match when names are duplicated", function()
			local universe1 = UniverseSummary:new({ directory = "/dir-1", uuid = "uuid-1", name = "name-1", lastExplored = 1 })
			local universe2 = UniverseSummary:new({ directory = "/dir-2", uuid = "uuid-2", name = "name-1", lastExplored = 2 })
			local m = Multiverse:new({ universe1, universe2 })
			m:removeUniverse("name-1")
			assert.are.equal(1, #m.universes)
			assert.are.equal(universe2, m.universes[1])
		end)

		it("should raise when universes was never set", function()
			local m = Multiverse:new(nil)
			assert.has_error(function()
				m:removeUniverse("name-1")
			end)
		end)
	end)
end)
